module decoder_4to16(
    input [3:0] bin,
    input en,
    output reg [15:0] dec
    );

    always @(*) begin
        if (en) begin
            case (bin)
                4'b0000: dec = 16'b0000000000000001; // 0000 -> 0000000000000001
                4'b0001: dec = 16'b0000000000000010; // 0001 -> 0000000000000010
                4'b0010: dec = 16'b0000000000000100; // 0010 -> 0000000000000100
                4'b0011: dec = 16'b0000000000001000; // 0011 -> 0000000000001000
                4'b0100: dec = 16'b0000000000010000; // 0100 -> 0000000000010000
                4'b0101: dec = 16'b0000000000100000; // 0101 -> 0000000000100000
                4'b0110: dec = 16'b0000000001000000; // 0110 -> 0000000001000000
                4'b0111: dec = 16'b0000000010000000; // 0111 -> 0000000010000000
                4'b1000: dec = 16'b0000000100000000; // 1000 -> 0000000100000000
                4'b1001: dec = 16'b0000001000000000; // 1001 -> 0000001000000000
                4'b1010: dec = 16'b0000010000000000; // 1010 -> 0000010000000000
                4'b1011: dec = 16'b0000100000000000; // 1011 -> 0000100000000000
                4'b1100: dec = 16'b0001000000000000; // 1100 -> 0001000000000000
                4'b1101: dec = 16'b0010000000000000; // 1101 -> 0010000000000000
                4'b1110: dec = 16'b0100000000000000; // 1110 -> 0100000000000000
                4'b1111: dec = 16'b1000000000000000; // 1111 -> 1000000000000000
                default: dec = 16'b0000000000000000; // Default to 0
            endcase
        end else
            dec = 16'b0000000000000000; // All zeros when disabled
    end
endmodule