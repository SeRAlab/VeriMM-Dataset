module qam_modulator(
    input [3:0] symbol,
    output reg signed [3:0] I,
    output reg signed [3:0] Q
);
    always @ (symbol) begin
        case(symbol)
            4'b0000: {I, Q} = {4'b0001, 4'b0001};
            4'b0001: {I, Q} = {4'b0001, 4'b0000};
            4'b0010: {I, Q} = {4'b0001, 4'b1111};
            4'b0011: {I, Q} = {4'b0000, 4'b0001};
            4'b0100: {I, Q} = {4'b0000, 4'b0000};
            4'b0101: {I, Q} = {4'b0000, 4'b1111};
            4'b0110: {I, Q} = {4'b1111, 4'b0001};
            4'b0111: {I, Q} = {4'b1111, 4'b0000};
            4'b1000: {I, Q} = {4'b1111, 4'b1111};
            4'b1001: {I, Q} = {4'b0000, 4'b1111};
            4'b1010: {I, Q} = {4'b0001, 4'b1111};
            4'b1011: {I, Q} = {4'b0000, 4'b0001};
            4'b1100: {I, Q} = {4'b1111, 4'b0001};
            4'b1101: {I, Q} = {4'b0001, 4'b0000};
            4'b1110: {I, Q} = {4'b0001, 4'b0001};
            4'b1111: {I, Q} = {4'b0000, 4'b0000};
            default: {I, Q} = {4'b0000, 4'b0000};
        endcase
    end
endmodule