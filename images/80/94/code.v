module top_module(
    input [15:0] A,
    input [3:0] shift,
    output reg [15:0] Y
);always @(*) begin
    case(shift)
        4'b0000: Y = A;
        4'b0001: Y = {A[14:0], A[15]};
        4'b0010: Y = {A[13:0], A[15:14]};
        4'b0011: Y = {A[12:0], A[15:13]};
        4'b0100: Y = {A[11:0], A[15:12]};
        4'b0101: Y = {A[10:0], A[15:11]};
        4'b0110: Y = {A[9:0], A[15:10]};
        4'b0111: Y = {A[8:0], A[15:9]};
        4'b1000: Y = {A[7:0], A[15:8]};
        4'b1001: Y = {A[6:0], A[15:7]};
        4'b1010: Y = {A[5:0], A[15:6]};
        4'b1011: Y = {A[4:0], A[15:5]};
        4'b1100: Y = {A[3:0], A[15:4]};
        4'b1101: Y = {A[2:0], A[15:3]};
        4'b1110: Y = {A[1:0], A[15:2]};
        4'b1111: Y = {A[0], A[15:1]};
    endcase
end

endmodule