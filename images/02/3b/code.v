module qam_modulator (
    input [3:0] data,
    output reg [3:0] I,
    output reg [3:0] Q
);
    always @(*) begin
        case(data)
            4'b0000: {I, Q} = {4'b0001, 4'b0001}; // (1, 1)
            4'b0001: {I, Q} = {4'b0001, 4'b0011}; // (1, 3)
            4'b0010: {I, Q} = {4'b0011, 4'b0001}; // (3, 1)
            4'b0011: {I, Q} = {4'b0011, 4'b0011}; // (3, 3)
            4'b0100: {I, Q} = {4'b0001, 4'b1111}; // (1, -1)
            4'b0101: {I, Q} = {4'b0001, 4'b1101}; // (1, -3)
            4'b0110: {I, Q} = {4'b0011, 4'b1111}; // (3, -1)
            4'b0111: {I, Q} = {4'b0011, 4'b1101}; // (3, -3)
            4'b1000: {I, Q} = {4'b1111, 4'b0001}; // (-1, 1)
            4'b1001: {I, Q} = {4'b1111, 4'b0011}; // (-1, 3)
            4'b1010: {I, Q} = {4'b1101, 4'b0001}; // (-3, 1)
            4'b1011: {I, Q} = {4'b1101, 4'b0011}; // (-3, 3)
            4'b1100: {I, Q} = {4'b1111, 4'b1111}; // (-1, -1)
            4'b1101: {I, Q} = {4'b1111, 4'b1101}; // (-1, -3)
            4'b1110: {I, Q} = {4'b1101, 4'b1111}; // (-3, -1)
            4'b1111: {I, Q} = {4'b1101, 4'b1101}; // (-3, -3)
            default: {I, Q} = 8'b00000000; // Default case
        endcase
    end
endmodule