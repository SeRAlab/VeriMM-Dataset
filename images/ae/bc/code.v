module top_module(
    input [255:0] in, // 256 inputs packed into 8 32-bit input vectors
    input [7:0] sel, // Selection input for the 256-to-1 multiplexer
    input [3:0] key_hi, // Upper 4 bits of the key generated by the barrel shifter
    input [3:0] key_lo, // Lower 4 bits of the key generated by the barrel shifter
    output reg [7:0] encrypted_msg // Encrypted message with a length of 8 bits
);// 256-to-1 multiplexer
wire [31:0] selected_input = in[sel*32 +: 32]; // Select 32 bits based on the 8-bit selector

// Barrel shifter
// Correctly split selected input into two 4-bit outputs without array indexing
wire [7:0] shifted_input = {selected_input[3:0], selected_input[7:4]}; // Combine the needed bits for encryption
wire [7:0] key = {key_hi, key_lo}; // Combine upper and lower 4 bits to form 8-bit key

// Custom encryption algorithm
always @(*) begin
    encrypted_msg = shifted_input ^ key; // XOR shifted input with key to encrypt
end

endmodule