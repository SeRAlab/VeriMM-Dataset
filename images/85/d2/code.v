module top_module(
    input [15:0] A,
    input [15:0] B,
    input [3:0] SHIFT,
    output reg [15:0] S
);always @(*) begin
    case(SHIFT)
        4'b0000: S = A;
        4'b0001: S = {A[14:0], A[15]};
        4'b0010: S = {A[13:0], A[15:14]};
        4'b0011: S = {A[12:0], A[15:13]};
        4'b0100: S = {A[11:0], A[15:12]};
        4'b0101: S = {A[10:0], A[15:11]};
        4'b0110: S = {A[9:0], A[15:10]};
        4'b0111: S = {A[8:0], A[15:9]};
        4'b1000: S = {A[7:0], A[15:8]};
        4'b1001: S = {A[6:0], A[15:7]};
        4'b1010: S = {A[5:0], A[15:6]};
        4'b1011: S = {A[4:0], A[15:5]};
        4'b1100: S = {A[3:0], A[15:4]};
        4'b1101: S = {A[2:0], A[15:3]};
        4'b1110: S = {A[1:0], A[15:2]};
        4'b1111: S = {A[0], A[15:1]};
        default: S = A;
    endcase
    if(B != 16'h0000) begin
        S = S | B;
    end
end

endmodule