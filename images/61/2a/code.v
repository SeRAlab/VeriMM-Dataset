module top_module(
  input clk,
  input rst,
  input [w-1:0] max_val,
  output reg [w-1:0] rand_num
);parameter w = 8; // number of bits in the output random number

reg [w-1:0] lfsr; // linear feedback shift register
reg [w-1:0] rand_bits; // random bits generated by the LFSR

// LFSR feedback polynomial
parameter [w-1:0] feedback_poly = {w{1'b1}} ^ {1'b1, w-1'b1, w-2'b1, w-5'b1};

always @(posedge clk) begin
  if (rst) begin
    lfsr <= {w{1'b0}}; // reset the LFSR to all zeros
  end else begin
    // generate the next random bit using the LFSR
    rand_bits <= lfsr[w-1] ^ lfsr[w-2] ^ lfsr[w-5] ^ lfsr[w-6];
    lfsr <= {lfsr[w-2:0], rand_bits}; // shift in the new random bit
  end
end

always @(posedge clk) begin
  if (rst) begin
    rand_num <= {w{1'b0}}; // reset the output to all zeros
  end else begin
    // generate a random number between 0 and max_val
    rand_num <= rand_bits % (max_val + 1);
  end
end

endmodule