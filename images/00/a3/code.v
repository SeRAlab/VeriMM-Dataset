module encoder_16_to_4 (
    input [15:0] in,
    output reg [3:0] out
);
    always @(*) begin
        case (in)
            16'b0000_0000_0000_0000: out = 4'b0000; // No active input
            16'b0000_0000_0000_0001: out = 4'b0000;
            16'b0000_0000_0000_0010: out = 4'b0001;
            16'b0000_0000_0000_0100: out = 4'b0010;
            16'b0000_0000_0000_1000: out = 4'b0011;
            16'b0000_0000_0001_0000: out = 4'b0100;
            16'b0000_0001_0000_0000: out = 4'b0101;
            16'b0000_0010_0000_0000: out = 4'b0110;
            16'b0000_0100_0000_0000: out = 4'b0111;
            16'b0000_1000_0000_0000: out = 4'b1000;
            16'b0001_0000_0000_0000: out = 4'b1001;
            16'b0010_0000_0000_0000: out = 4'b1010;
            16'b0100_0000_0000_0000: out = 4'b1011;
            16'b1000_0000_0000_0000: out = 4'b1100;
            16'b1111_1111_1111_1111: out = 4'b1111; // last case for full input
            default: out = 4'b0000; // for any other cases
        endcase
    end
endmodule