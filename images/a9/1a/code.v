    input [3:0] BIN,
    output reg [15:0] BCD
);always @(*) begin
    case(BIN)
        4'b0000: BCD = 16'b0000000000000000;
        4'b0001: BCD = 16'b0000000000000001;
        4'b0010: BCD = 16'b0000000000000010;
        4'b0011: BCD = 16'b0000000000000011;
        4'b0100: BCD = 16'b0000000000000100;
        4'b0101: BCD = 16'b0000000000000101;
        4'b0110: BCD = 16'b0000000000000110;
        4'b0111: BCD = 16'b0000000000000111;
        4'b1000: BCD = 16'b0000000000010000;
        4'b1001: BCD = 16'b0000000000010001;
        4'b1010: BCD = 16'b0000000000010010;
        4'b1011: BCD = 16'b0000000000010011;
        4'b1100: BCD = 16'b0000000000010100;
        4'b1101: BCD = 16'b0000000000010101;
        4'b1110: BCD = 16'b0000000000010110;
        4'b1111: BCD = 16'b0000000000010111;
    endcase
end

endmodule