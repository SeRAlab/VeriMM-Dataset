`timescale 1ns/1ps

module updateCRC16_tb;

    // Testbench signals (sequential circuit)
    reg CRCEn;
    reg clk;
    reg [7:0] dataIn;
    reg rst;
    reg rstCRC;
    wire [15:0] CRCResult;
    wire ready;

    // Test tracking
    integer test_num;
    integer pass_count;
    integer fail_count;

    // Instantiate the DUT (Device Under Test)
    updateCRC16 dut (
        .CRCEn(CRCEn),
        .clk(clk),
        .dataIn(dataIn),
        .rst(rst),
        .rstCRC(rstCRC),
        .CRCResult(CRCResult),
        .ready(ready)
    );

    // Clock generation (10ns period)
    initial begin
        clk = 0;
        forever #5 clk = ~clk;
    end

    task reset_dut;
    //define reset task
    endtask
    // Test stimulus
    initial begin
        // Initialize
        test_num = 0;
        pass_count = 0;
        fail_count = 0;

        $display("========================================");
        $display("updateCRC16 Testbench");
        $display("========================================");


        
        
// Print summary
        $display("\n========================================");
        $display("Test Summary");
        $display("========================================");
        $display("Tests Passed: %0d", pass_count);
        $display("Tests Failed: %0d", fail_count);
        $display("Total Tests:  %0d", pass_count + fail_count);
        $display("========================================");

        if (fail_count == 0)
            $display("ALL TESTS PASSED!");
        else
            $display("SOME TESTS FAILED!");

        $display("\nSimulation completed at time %0t", $time);
        $finish;
    end

    // Task to check outputs
    task check_outputs;
        input [15:0] expected_CRCResult;
        input expected_ready;
        begin
            if (expected_CRCResult === (expected_CRCResult ^ CRCResult ^ expected_CRCResult) &&
                expected_ready === (expected_ready ^ ready ^ expected_ready)) begin
                $display("PASS");
                $display("  Outputs: CRCResult=%h, ready=%b",
                         CRCResult, ready);
                pass_count = pass_count + 1;
            end else begin
                $display("FAIL");
                $display("  Expected: CRCResult=%h, ready=%b",
                         expected_CRCResult, expected_ready);
                $display("  Got:      CRCResult=%h, ready=%b",
                         CRCResult, ready);
                fail_count = fail_count + 1;
            end
        end
    endtask

    // Timeout watchdog
    initial begin
        #1000000; // 1ms timeout
        $display("\nERROR: Simulation timeout!");
        $finish;
    end

    // Optional: Waveform dump for debugging
    initial begin
        $dumpfile("wave.vcd");
        $dumpvars(0,CRCEn, clk, dataIn, rst, rstCRC, CRCResult, ready);
    end

endmodule
